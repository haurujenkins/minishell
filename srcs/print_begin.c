#include "minishell.h"

void	loading(int p)
{	
	int i;

	i = 0;
	printf("[");
	while (i < 50)
	{
		if (i < p / 2)
			printf("=");
		else
            printf(" ");
		i++;
	}
	printf("] %d%%\r", p);
}

